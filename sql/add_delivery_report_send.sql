CREATE TABLE IF NOT EXISTS delivery_report_send (
    report_date DATE NOT NULL PRIMARY KEY COMMENT '北京时间的日报日期',
    status VARCHAR(16) NOT NULL COMMENT 'SENDING, SENT, FAILED, UNKNOWN',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    sent_at DATETIME DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='正式货期日报发送记录';
